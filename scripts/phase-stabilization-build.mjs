import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = process.cwd();
const canonicalSources = [
  'calculators.js',
  'widget.js',
  'wa-core.js',
  'calculator-runtime.js',
  'site-runtime.js',
  'final-polish.js',
  'wa-enhancements.js',
  'theme-fix.js',
  'phase2-intelligence.js',
  'phase2-retirement.js',
  'phase3-seo.js',
  'calculator-page-init.js',
  'phase4-premium.js',
];

const calculatorPages = [
  'sip-calculator.html', 'compound-interest-calculator.html', 'mortgage-emi-calculator.html',
  'roi-calculator.html', 'simple-interest-calculator.html', 'retirement-calculator.html',
  'salary-to-hourly-calculator.html', 'profit-margin-calculator.html', 'fixed-deposit-calculator.html',
  'recurring-deposit-calculator.html', 'lumpsum-calculator.html', 'cagr-calculator.html',
  'car-loan-calculator.html', 'personal-loan-calculator.html', 'debt-payoff-calculator.html',
  'inflation-calculator.html', 'net-worth-calculator.html', 'overtime-pay-calculator.html',
  'freelance-rate-calculator.html', 'income-tax-scenario-calculator.html',
];

for (const file of canonicalSources) {
  if (!fs.existsSync(path.join(root, file))) throw new Error(`Missing canonical runtime source: ${file}`);
}

const stamp = new Date().toISOString().slice(0, 10).replaceAll('-', '');
const sourceParts = canonicalSources.map(file => {
  const content = fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n').trimEnd();
  const sha = crypto.createHash('sha256').update(content).digest('hex').slice(0, 12);
  return `/* ===== WA CANONICAL MODULE: ${file} | sha256:${sha} ===== */\n${content}\n`;
});
const bundle = `/* Wealth Arrays canonical calculator runtime bundle.\n * Generated by scripts/phase-stabilization-build.mjs.\n * Source order is intentional: preserve the current production execution order.\n * Build date: ${stamp}\n */\n(function(){\n  if (window.__WA_CANONICAL_RUNTIME_BUNDLE__) return;\n  window.__WA_CANONICAL_RUNTIME_BUNDLE__ = true;\n})();\n\n${sourceParts.join('\n')}`;
const bundlePath = path.join(root, 'wa-calculator-runtime.js');
fs.writeFileSync(bundlePath, bundle, 'utf8');

const managedBasenames = new Set(canonicalSources);
let changed = 0;
for (const file of calculatorPages) {
  const full = path.join(root, file);
  if (!fs.existsSync(full)) throw new Error(`Missing calculator page: ${file}`);
  let html = fs.readFileSync(full, 'utf8');
  const before = html;
  html = html.replace(/\s*<script\s+src=["']([^"']+)["'][^>]*><\/script>/gi, (tag, src) => {
    const base = path.basename(src.split('?', 1)[0]);
    return managedBasenames.has(base) ? '' : tag;
  });
  const canonicalTag = '<script src="/wa-calculator-runtime.js?v=20260916-stable" defer></script>';
  if (!html.includes(canonicalTag)) {
    if (!/<script\s+src=["'][^"']*wa-calculator-runtime\.js[^"']*["'][^>]*><\/script>/i.test(html)) {
      html = html.replace('</body>', `${canonicalTag}</body>`);
    } else {
      html = html.replace(/\s*<script\s+src=["'][^"']*wa-calculator-runtime\.js[^"']*["'][^>]*><\/script>/i, `\n${canonicalTag}`);
    }
  }
  html = html.replace(/\s*<!-- WA-CANONICAL-RUNTIME:[^>]+-->\s*/g, '\n');
  html = html.replace(/(<body[^>]*>)/i, `$1\n<!-- WA-CANONICAL-RUNTIME:v1 -->`);
  if (html !== before) {
    fs.writeFileSync(full, html, 'utf8');
    changed += 1;
  }
}

// Keep development/test dependencies out of the deployable GitHub Pages repository.
if (fs.existsSync(path.join(root, 'node_modules'))) fs.rmSync(path.join(root, 'node_modules'), { recursive: true, force: true });
const gitignore = path.join(root, '.gitignore');
let ignore = fs.existsSync(gitignore) ? fs.readFileSync(gitignore, 'utf8') : '';
const required = ['node_modules/', '.DS_Store'];
for (const item of required) if (!ignore.split(/\r?\n/).includes(item)) ignore += `${ignore.endsWith('\n') || !ignore ? '' : '\n'}${item}\n`;
fs.writeFileSync(gitignore, ignore, 'utf8');

console.log(`Stabilization build complete — canonical runtime bundle generated; ${changed} calculator pages normalized; local node_modules removed/ignored.`);
